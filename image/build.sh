#!/usr/bin/env bash
# Build the weather-pi device image with a pinned pi-gen checkout.
#
# The build is opt-in and needs a working Docker daemon with privileged
# container support: pi-gen creates loop devices and runs the armhf chroot
# through QEMU. The repository URL and archive keyring are inputs because the
# image installs packages from the signed apt repository.
#
#   IMAGE_VERSION=0.2.0-1 \
#   WEATHER_PI_REPO_URL=https://example.invalid/weather-pi/ \
#   WEATHER_PI_ARCHIVE_KEYRING=packaging/keyring/weather-pi-archive.gpg \
#   WEATHER_PI_MINISIGN_KEY="$HOME/.minisign/weather-pi.key" \
#   mise run image
#
# IMAGE_VERSION defaults to `scripts/version.sh from-git`. IMAGE_PREPARE_ONLY=1
# stops after the pi-gen tree and the stage are assembled, which inspects the
# payload without a Docker build and works on hosts without Docker.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Pinned upstream revision of RPi-Distro/pi-gen: the armhf, trixie release tag
# 2026-10-06-raspios-trixie-armhf.
PIGEN_REPO="${PIGEN_REPO:-https://github.com/RPi-Distro/pi-gen.git}"
PIGEN_REV="${PIGEN_REV:-291c62c1108d03f594dbed65507e97eb0d9a2b0e}"

IMAGE_BUILD_DIR="${IMAGE_BUILD_DIR:-$repo_root/target/image}"
IMAGE_OUTPUT_DIR="${IMAGE_OUTPUT_DIR:-$repo_root/dist/image}"
PIGEN_DIR="$IMAGE_BUILD_DIR/pi-gen"
STAGE_NAME="stage-weather-pi"
STAGE_SRC="$repo_root/image/$STAGE_NAME"
CONFIG="$IMAGE_BUILD_DIR/config"

IMAGE_VERSION="${IMAGE_VERSION:-$(cd "$repo_root" && scripts/version.sh from-git)}"
REPO_URL="${WEATHER_PI_REPO_URL:-https://corrodedhash.github.io/weather-pi/}"
KEYRING="${WEATHER_PI_ARCHIVE_KEYRING:-$repo_root/packaging/keyring/weather-pi-archive.gpg}"
MINISIGN_KEY="${WEATHER_PI_MINISIGN_KEY:-}"
MINISIGN_PUBKEY="${WEATHER_PI_MINISIGN_PUBKEY:-$repo_root/packaging/image-signing.pub}"

die() {
    echo "image/build.sh: $*" >&2
    exit 1
}

need() {
    command -v "$1" >/dev/null 2>&1 || die "required tool '$1' is not installed"
}

escape_sed() {
    printf '%s' "$1" | sed -e 's/[\\&|]/\\&/g'
}

[[ -n "$IMAGE_VERSION" ]] || die "IMAGE_VERSION is empty"
[[ "$IMAGE_VERSION" =~ ^[A-Za-z0-9.+:~_-]+$ ]] ||
    die "IMAGE_VERSION '$IMAGE_VERSION' contains characters unsafe for a package version or filename"
[[ -n "$PIGEN_REV" ]] || die "PIGEN_REV is empty"

need git

[[ -d "$STAGE_SRC" ]] || die "stage source not found at $STAGE_SRC"
[[ -s "$KEYRING" ]] || die "archive keyring not found at $KEYRING
Export the public archive key first, or set WEATHER_PI_ARCHIVE_KEYRING."

mkdir -p "$IMAGE_BUILD_DIR"

if [[ ! -d "$PIGEN_DIR/.git" ]]; then
    rm -rf "$PIGEN_DIR"
    git clone --filter=blob:none "$PIGEN_REPO" "$PIGEN_DIR"
fi

if ! git -C "$PIGEN_DIR" cat-file -e "$PIGEN_REV^{commit}" 2>/dev/null; then
    git -C "$PIGEN_DIR" fetch --depth 1 origin "$PIGEN_REV"
fi
git -C "$PIGEN_DIR" checkout --detach --force "$PIGEN_REV"
git -C "$PIGEN_DIR" clean -ffdx
resolved_pigen_rev="$(git -C "$PIGEN_DIR" rev-parse HEAD)"

# The stage is copied into the pi-gen tree so build-docker.sh can see it from
# inside the container; pi-gen does not mount arbitrary host directories.
rm -rf "${PIGEN_DIR:?}/$STAGE_NAME"
cp -a "$STAGE_SRC" "$PIGEN_DIR/$STAGE_NAME"
install -D -m 0644 "$KEYRING" \
    "$PIGEN_DIR/$STAGE_NAME/00-apt/files/usr/share/keyrings/weather-pi-archive.gpg"

# The stage and the chroot scan use one implementation of the secret check.
install -D -m 0755 "$repo_root/scripts/check-image-secrets.sh" \
    "$PIGEN_DIR/$STAGE_NAME/90-secret-scan/files/usr/lib/weather-pi/check-image-secrets"

# The image-version file is generated, not committed: it binds the installed
# package version and the exact pi-gen commit into the build-info written by
# 20-packages/01-run-chroot.sh.
version_dir="$PIGEN_DIR/$STAGE_NAME/20-packages/files/etc/weather-pi"
mkdir -p "$version_dir"
cat >"$version_dir/image-version" <<EOF
# Generated by image/build.sh. One key=value pair per line.
IMAGE_VERSION=$IMAGE_VERSION
PIGEN_REV=$resolved_pigen_rev
EOF
chmod 0644 "$version_dir/image-version"

repo_url_escaped="$(escape_sed "$REPO_URL")"
while IFS= read -r file; do
    sed -i "s|@WEATHER_PI_REPO_URL@|$repo_url_escaped|g" "$file"
done < <(grep -rlF '@WEATHER_PI_REPO_URL@' "$PIGEN_DIR/$STAGE_NAME")

# Fail before a long Docker build if the staged payload contains a credential.
"$repo_root/scripts/check-image-secrets.sh" "$PIGEN_DIR/$STAGE_NAME"

# stage2 would otherwise export its own intermediate image.
touch "$PIGEN_DIR/stage2/SKIP_IMAGES"

cp "$repo_root/image/config" "$CONFIG"

if [[ "${IMAGE_PREPARE_ONLY:-0}" == "1" ]]; then
    echo "pi-gen prepared at $PIGEN_DIR"
    echo "stage prepared at $PIGEN_DIR/$STAGE_NAME"
    echo "config prepared at $CONFIG"
    echo "image version prepared at $version_dir/image-version"
    exit 0
fi

# Validate the build and signing inputs before spending an hour in Docker.
need docker
need zstd
need minisign
[[ -n "$MINISIGN_KEY" ]] ||
    die "WEATHER_PI_MINISIGN_KEY is not set; the published image must be signed"
[[ -s "$MINISIGN_KEY" ]] || die "minisign secret key not found at $MINISIGN_KEY"
if [[ -n "${WEATHER_PI_MINISIGN_PUBKEY:-}" ]]; then
    [[ -s "$MINISIGN_PUBKEY" ]] ||
        die "WEATHER_PI_MINISIGN_PUBKEY is set but not found at $MINISIGN_PUBKEY"
fi

rm -rf "$PIGEN_DIR/deploy"

(
    cd "$PIGEN_DIR"
    ./build-docker.sh -c "$CONFIG"
)

mapfile -t images < <(find "$PIGEN_DIR/deploy" -maxdepth 1 -type f -name '*.img' -print)
[[ ${#images[@]} -eq 1 ]] ||
    die "expected exactly one .img in $PIGEN_DIR/deploy, found ${#images[@]}"

image="${images[0]}"
mkdir -p "$IMAGE_OUTPUT_DIR"
output="$IMAGE_OUTPUT_DIR/weather-pi-${IMAGE_VERSION}.img.zst"

echo "==> Compressing $image"
zstd -q -f -T0 -19 -o "$output" "$image"

echo "==> Writing SHA256SUMS"
(cd "$IMAGE_OUTPUT_DIR" && sha256sum "$(basename "$output")" >SHA256SUMS)

echo "==> Signing $(basename "$output")"
minisign -S -s "$MINISIGN_KEY" -m "$output" -x "${output}.minisig" \
    -t "weather-pi ${IMAGE_VERSION} image"

if [[ -s "$MINISIGN_PUBKEY" ]]; then
    minisign -V -m "$output" -x "${output}.minisig" -p "$MINISIGN_PUBKEY"
fi

echo
echo "Image artifacts in $IMAGE_OUTPUT_DIR:"
ls -1 "$output" "${output}.minisig" "$IMAGE_OUTPUT_DIR/SHA256SUMS"
